namespace OpenKustoExplorer.Presentation.Workbench;

/// <summary>
/// Identifies the unit used to configure an automation recurrence interval.
/// </summary>
public enum KustoAutomationIntervalUnit
{
    /// <summary>
    /// Recurs every configured number of minutes.
    /// </summary>
    Minutes,

    /// <summary>
    /// Recurs every configured number of hours.
    /// </summary>
    Hours,

    /// <summary>
    /// Recurs every configured number of days.
    /// </summary>
    Days,
}
